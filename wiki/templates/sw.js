/* Service worker for Walter's AP Chem — makes the site work offline as an app.
   Generated by wiki/pwa.py from wiki/templates/sw.js on every build (edit the template).

   Caches
     apchem-pages-<VERSION>  every page + asset, downloaded when a new version installs
     apchem-media            notebook scans + reference PDFs (kept across updates; filled when
                             viewed or by Settings → "Save all for offline")
     apchem-cdn              Mermaid (the only library still loaded from a CDN)
   Strategies
     pages      network first (newest notes when online), saved copy when offline/slow
     assets     saved copy first (their URLs change when the file changes: ?v=…)
     search     saved copy, refreshed in the background
     media/cdn  saved copy first, otherwise download and keep */
const VERSION = "__VERSION__";
const PAGES = "apchem-pages-" + VERSION;
const MEDIA = "apchem-media";
const CDN = "apchem-cdn";
const FILES = __PRECACHE__;
const SCOPE = self.registration.scope;
const abs = (p) => new URL(p, SCOPE).href;
const OFFLINE_PAGE = abs("offline/");
const NETWORK_TIMEOUT = 3500;

// clean copy (no "redirected" flag: Safari refuses those for page loads)
async function clean(res) {
  if (!res.redirected) return res;
  return new Response(await res.blob(), { status: res.status, statusText: res.statusText, headers: res.headers });
}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(PAGES);
    const urls = FILES.map(abs);
    for (let i = 0; i < urls.length; i += 6) {
      await Promise.all(urls.slice(i, i + 6).map(async (u) => {
        const res = await fetch(u, { cache: "reload" });
        if (!res.ok) throw new Error("precache failed: " + u + " " + res.status);
        await cache.put(u, await clean(res));
      }));
    }
    await self.skipWaiting(); // use the new version right away; pages show "Updated — Refresh"
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith("apchem-pages-") && key !== PAGES) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});

self.addEventListener("message", (event) => {
  if (event.data === "version" && event.source) event.source.postMessage({ type: "version", version: VERSION });
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin) {
    if (!req.url.startsWith(SCOPE) || url.pathname.endsWith("/__version")) return; // dev server live reload
    if (req.mode === "navigate") return event.respondWith(page(req));
    if (/\/assets\/(scans|resources)\//.test(url.pathname)) return event.respondWith(media(req));
    if (url.pathname.endsWith("/search-index.json") || url.pathname.endsWith("/offline-media.json")) {
      return event.respondWith(fresh(req, PAGES));
    }
    return event.respondWith(asset(req));
  }
  if (url.hostname === "cdn.jsdelivr.net") return event.respondWith(fresh(req, CDN));
});

// pages: the network when it answers quickly, otherwise the saved copy
async function page(req) {
  const cache = await caches.open(PAGES);
  const net = fetch(req).then(async (res) => {
    if (res.ok && res.type === "basic") await cache.put(req.url.split("#")[0], (await clean(res)).clone()).catch(() => {});
    return res;
  });
  net.catch(() => {}); // when the saved copy wins, a later network failure is fine
  const saved = () => caches.match(req, { ignoreSearch: true }); // pages, or a saved scan/PDF opened directly
  try {
    const timer = new Promise((resolve) => setTimeout(() => resolve("slow"), NETWORK_TIMEOUT));
    const first = await Promise.race([net, timer]);
    if (first !== "slow") return first;
    const hit = await saved();
    if (hit) return hit;
    return await net;
  } catch (err) {
    const hit = await saved();
    if (hit) return hit;
    // go to the offline page by its own address, so its links and styles resolve correctly
    if (await caches.match(OFFLINE_PAGE)) return Response.redirect(OFFLINE_PAGE, 302);
    return new Response("You're offline.", { status: 503, headers: { "Content-Type": "text/plain" } });
  }
}

// versioned assets: saved copy first
async function asset(req) {
  const hit = await caches.match(req);
  if (hit) return hit;
  try {
    return await fetch(req);
  } catch (err) {
    return (await caches.match(req, { ignoreSearch: true })) || Response.error();
  }
}

// scans + PDFs: saved copy first, otherwise download and keep
async function media(req) {
  const cache = await caches.open(MEDIA);
  const hit = await cache.match(req, { ignoreSearch: true });
  if (hit) return hit;
  try {
    const res = await fetch(req);
    if (res.ok && res.status === 200 && !req.headers.has("range")) await cache.put(req, res.clone()).catch(() => {});
    return res;
  } catch (err) {
    return Response.error(); // not saved yet and no connection
  }
}

// saved copy now, refresh it in the background
async function fresh(req, name) {
  const cache = await caches.open(name);
  const hit = await cache.match(req, { ignoreSearch: name === PAGES });
  const update = fetch(req).then(async (res) => {
    if (res.ok) await cache.put(req, res.clone()).catch(() => {});
    return res;
  }).catch(() => null);
  return hit || (await update) || Response.error();
}
